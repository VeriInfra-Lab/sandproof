class ReceiptProjectAdmissionTests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root=Path(self.temp.name)

    def test_existing_cache_and_original_git_identity_are_preserved(self):
        project=self.root/'project'
        (project/'.lake/build').mkdir(parents=True)
        (project/'.lake/build/cache').write_bytes(b'old Lean cache')
        (project/'.git').mkdir()
        (project/'.git/HEAD').write_text('original private identity\n')
        (project/'source.txt').write_bytes(b'previous draft')
        with mock.patch.object(support.subprocess,'check_output',return_value='old-head\n'):
            row=support.prepare_project(project,{'source.txt':b'current archived source'},
                {'source.txt':0o644},existing=True,history=self.root/'history')
        self.assertEqual(row['previous_git_head'],'old-head')
        self.assertEqual((project/'.git/HEAD').read_text(),'original private identity\n')
        self.assertEqual((project/'.lake/build/cache').read_bytes(),b'old Lean cache')
        self.assertEqual((self.root/'history/source.txt').read_bytes(),b'previous draft')
        self.assertEqual((project/'source.txt').read_bytes(),b'current archived source')
        self.assertEqual((project/'source.txt').stat().st_mode&0o777,0o644)

    def test_linked_project_and_parent_are_rejected(self):
        actual=self.root/'actual'
        actual.mkdir()
        alias=self.root/'alias'
        alias.symlink_to(actual,target_is_directory=True)
        for name in (alias,alias/'child'):
            with self.subTest(path=name),self.assertRaises(ValueError):
                support.prepare_project(name,{}, {},existing=True)

    def test_unarchived_rust_is_not_deleted_or_admitted(self):
        project=self.root/'project'
        project.mkdir()
        extra=project/'unknown.rs'
        extra.write_text('unregistered source')
        with self.assertRaisesRegex(ValueError,'Unarchived'):
            support.prepare_project(project,{}, {},existing=True)
        self.assertEqual(extra.read_text(),'unregistered source')


class ReceiptCaptureAdmissionTests(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root=Path(self.temp.name)
        self.origin=self.root/'origin'
        self.project=self.root/'project'
        self.original=self.root/'original'
        for path in (self.origin,self.project,self.original): path.mkdir()
        self.names={'Cargo.toml':b'[workspace]\n','Cargo.lock':b'fixed lock',
            'controller-core/Cargo.toml':b'[package]\nname="fixture"\n',
            'controller-core/src/effect.rs':b'original synthetic Rust bytes'}
        for name,data in self.names.items():
            path=self.project/name
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_bytes(data)
            path.chmod(0o644)
        for name,data in {'capture_handoff.llbc':b'original synthetic IR',
                'checkout-candidate.log':b'original source checkout',
                'charon.log':b'original frontend log','aeneas.log':b'original backend log',
                'lean/translation.json':b'synthetic translation',
                'lean/CaptureCaller/Types.lean':b'synthetic types',
                'lean/CaptureCaller/FunsExternal_Template.lean':b'synthetic external inventory',
                'lean/CaptureCaller/Funs.lean':b'synthetic generated bytes'}.items():
            path=self.origin/name
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_bytes(data)
        self.roots=('effect::receipt_pause',)
        frontend=['/fixed/charon','cargo','--preset=aeneas','--error-on-warnings','--sysroot','default',
            '--start-from','crate::effect::receipt_pause']
        for name in ('sandbox_controller_core','core::option::*::and_then','core::option::*::as_ref'):
            frontend+=['--include',name]
        frontend+=['--dest-file',str(self.origin/'capture_handoff.llbc'),'--','--manifest-path',
                   'Cargo.toml','--lib','--locked','--offline']
        backend=['/fixed/aeneas','-backend','lean','-abort-on-error','-warnings-as-errors',
            '-split-files','-emit-json','-namespace','CaptureCallerRust.sandbox_controller_core',
            '-subdir','CaptureCaller','-dest',str(self.origin/'lean'),str(self.origin/'capture_handoff.llbc')]
        self.record=dict(complete=True,scope_admitted=True,capture_complete=True,
            translation_complete=True,ordinary_tests_run=False,roots=list(self.roots),
            head='original-head',tree='original-tree',
            effect_sha256=self.digest(self.names['controller-core/src/effect.rs']),
            llbc_sha256=support.sha(self.origin/'capture_handoff.llbc'),
            commands=[dict(label='checkout-candidate',argv=['git','checkout'],cwd=str(self.original),exit_code=0,
                log_sha256=support.sha(self.origin/'checkout-candidate.log')),
                dict(label='charon',argv=frontend,cwd=str(self.original/'controller-core'),exit_code=0,
                    log_sha256=support.sha(self.origin/'charon.log')),
                dict(label='aeneas',argv=backend,cwd=str(self.original),exit_code=0,
                    log_sha256=support.sha(self.origin/'aeneas.log'))],
            outputs={str(p.relative_to(self.origin)):support.sha(p)
                for p in (self.origin/'lean').rglob('*') if p.is_file()})
        self.write_record()
        self.native=types.SimpleNamespace(SOURCE=Path('controller-core/src/effect.rs'))
        self.checks=types.SimpleNamespace(regular=lambda p:p,
            verify_generation=mock.Mock(return_value={}),literal_constant=lambda *args:set())

    @staticmethod
    def digest(data): return hashlib.sha256(data).hexdigest()

    def write_record(self):
        (self.origin/'result.json').write_text(json.dumps(self.record))

    def git(self,argv,**kwargs):
        if argv[1]=='rev-parse': return 'original-tree\n'
        if argv[1]=='ls-tree' and '--name-only'in argv:
            return '\n'.join(self.names)+'\n'
        if argv[1]=='ls-tree':
            return b'\0'.join(b'100644 blob unused\t'+name.encode()for name in self.names)+b'\0'
        if argv[1]=='show': return self.names[argv[2].split(':',1)[1]]
        raise AssertionError('unregistered synthetic git request')

    def admit(self):
        with mock.patch.object(support.subprocess,'check_output',side_effect=self.git):
            return support.admit_capture(self.origin,self.root/'accepted',self.project,
                role='correct',roots=self.roots,native=self.native,checks=self.checks)

    def test_unchanged_original_is_kept_as_capture_not_relabelled_proof(self):
        row=self.admit()
        self.assertEqual(row['original_head'],'original-head')
        self.assertEqual(row['kind'],'original_capture_reused_not_a_proof_receipt')
        self.assertEqual((self.root/'accepted/result.json').read_bytes(),
                         (self.origin/'result.json').read_bytes())

    def test_changed_rust_rejects_even_with_complete_old_record(self):
        (self.project/'controller-core/src/effect.rs').write_bytes(b'changed actual Rust')
        with self.assertRaisesRegex(ValueError,'compiler input changed'):
            self.admit()
        self.checks.verify_generation.assert_not_called()

    def test_new_or_missing_compiler_file_rejects(self):
        extra=self.project/'controller-core/src/new.rs'
        extra.write_bytes(b'unregistered')
        with self.assertRaisesRegex(ValueError,'file set changed'):
            self.admit()
        extra.unlink()
        (self.project/'Cargo.lock').unlink()
        with self.assertRaisesRegex(ValueError,'file set changed'):
            self.admit()

    def test_changed_compiler_file_mode_rejects(self):
        (self.project/'controller-core/src/effect.rs').chmod(0o755)
        with self.assertRaisesRegex(ValueError,'compiler input changed'):
            self.admit()

    def test_changed_original_generated_bytes_reject(self):
        (self.origin/'lean/CaptureCaller/Funs.lean').write_bytes(b'tampered output')
        with self.assertRaisesRegex(ValueError,'output changed'):
            self.admit()

    def test_failed_or_changed_producer_log_rejects(self):
        self.record['commands'][0]['exit_code']=1
        self.write_record()
        with self.assertRaisesRegex(ValueError,'incomplete/corrupt'):
            self.admit()

    def test_foreign_roots_or_incomplete_capture_reject(self):
        self.record['roots']=['unrelated::function']
        self.write_record()
        with self.assertRaisesRegex(ValueError,'twenty-root'):
            self.admit()

    def test_extra_compiler_flag_cannot_reuse_old_capture(self):
        self.record['commands'][1]['argv'].insert(2,'--skip-borrowck')
        self.write_record()
        with self.assertRaisesRegex(ValueError,'compiler flags'):
            self.admit()


