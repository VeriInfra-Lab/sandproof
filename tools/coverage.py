#!/usr/bin/env python3
"""Render the property -> monitorability -> checker-rule coverage report.

Usage:
  tools/coverage.py            # print to stdout
  tools/coverage.py --write     # also write artifacts/trace-coverage.md
"""
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from tools.model import properties
from tools.trace.rules import REGISTRY


def summary() -> str:
    implemented = {rule.name for rule in REGISTRY}
    counts = Counter(p.monitorability for p in properties.PROPERTIES)
    missing = [p.name for p in properties.PROPERTIES
               if p.monitorability == properties.MONITORABLE and not p.rule]
    lines = [
        "# Trace checker coverage",
        "",
        "Generated by `tools/coverage.py` from `tools/model/properties.py`.",
        "",
        f"Rules implemented: {', '.join(sorted(implemented)) or '—'}",
        "",
        "## Monitorability summary",
        "",
        "| class | count |",
        "|---|---|",
    ]
    for klass, count in sorted(counts.items()):
        lines.append(f"| {klass} | {count} |")
    if missing:
        lines += ["", "## Monitorable but not yet wired", ""]
        lines += [f"- `{name}`" for name in missing]
    lines += ["", "## Property matrix", "", properties.report(), ""]
    return "\n".join(lines)


def main() -> int:
    out = summary()
    print(out)
    if "--write" in sys.argv:
        root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        directory = os.path.join(root, "artifacts")
        os.makedirs(directory, exist_ok=True)
        path = os.path.join(directory, "trace-coverage.md")
        with open(path, "w") as handle:
            handle.write(out + "\n")
        print(f"wrote {path}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
