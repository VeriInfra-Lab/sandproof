"""Share unchanged large Torch wheels with the original uv verifier in its VM.

Only public package-manager interfaces write caches. Reinstall one wheel at a
time so the guest never needs two complete Torch/CUDA installations at once.
"""
import hashlib
import importlib.metadata as metadata
import json
from pathlib import Path
import re
import subprocess
import sys
import sysconfig
import tempfile
from urllib.parse import urlsplit

LARGE_FILE_BYTES = 64 * 1024**2


def normalize(name):
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]*', name):
        raise ValueError('invalid distribution name')
    return re.sub(r'[-_.]+', '-', name).lower()


def payload_files(dist):
    if not dist.files:
        raise ValueError('distribution has no file inventory')
    for relative in sorted(dist.files, key=str):
        path = Path(relative)
        # Installer metadata, generated bytecode and entrypoint scripts are
        # installer-specific; actual importable code/data must remain identical.
        if ('..' in path.parts or path.suffix == '.pyc'
                or any(p.endswith(('.dist-info', '.egg-info')) for p in path.parts)):
            continue
        if path.is_absolute():
            raise ValueError('absolute distribution payload path')
        installed = Path(dist.locate_file(relative))
        if installed.is_symlink() or not installed.is_file():
            raise ValueError('missing or nonregular distribution payload')
        yield path.as_posix(), installed


def snapshot(dist):
    digest = hashlib.sha256()
    large = []
    count = 0
    for relative, path in payload_files(dist):
        with path.open('rb') as incoming:
            content = hashlib.file_digest(incoming, 'sha256').hexdigest()
        digest.update((relative + '\0' + content + '\n').encode())
        stat = path.stat()
        if stat.st_size >= LARGE_FILE_BYTES:
            large.append({'path': relative, 'bytes': stat.st_size,
                          'sha256': content, 'links': stat.st_nlink})
        count += 1
    if not count:
        raise ValueError('empty distribution payload')
    return {'payload_sha256': digest.hexdigest(), 'payload_files': count, 'large_files': large}


def wheel_requirement(report, name, version):
    if not re.fullmatch(r'[A-Za-z0-9_.+!-]+', version):
        raise ValueError('invalid distribution version')
    items = report['install']
    if len(items) != 1:
        raise ValueError('expected exactly one wheel without dependency changes')
    item = items[0]
    if normalize(item['metadata']['name']) != normalize(name) or item['metadata']['version'] != version:
        raise ValueError('wheel resolution changed the installed version')
    download = item['download_info']
    url = urlsplit(download['url'])
    digest = download['archive_info']['hashes']['sha256']
    if (url.scheme != 'https' or url.hostname != 'files.pythonhosted.org'
            or url.username or url.password or url.port not in (None, 443)
            or not url.path.endswith('.whl') or not re.fullmatch('[0-9a-f]{64}', digest)):
        raise ValueError('expected a hashed public PyPI wheel')
    return f'{normalize(name)}=={version} --hash=sha256:{digest}\n'


def relink(name, version, requirements, uv):
    before_dist = metadata.distribution(name)
    if before_dist.version != version:
        raise ValueError('installed version changed before relinking')
    before = snapshot(before_dist)
    subprocess.run([str(uv), 'pip', 'install', '--system', '--python', sys.executable,
                    '--index-url', 'https://pypi.org/simple',
                    '--no-deps', '--require-hashes', '--link-mode', 'hardlink',
                    '--reinstall-package', name, '-r', str(requirements)], check=True)
    after_dist = metadata.distribution(name)
    after = snapshot(after_dist)
    if (after_dist.version != version
            or before['payload_sha256'] != after['payload_sha256']
            or before['payload_files'] != after['payload_files']):
        raise ValueError('reinstalled wheel changed code or data')
    if not after['large_files'] or any(row['links'] < 2 for row in after['large_files']):
        raise ValueError('large wheel files were not hard-linked to cache')
    return {'name': name, 'version': version, 'payload_unchanged': True, **after}


def installed_versions():
    return {normalize(d.metadata['Name']): d.version for d in metadata.distributions()}


def main():
    if sys.version_info[:2] != (3, 13) or metadata.version('torch') != '2.7.1':
        raise ValueError('expected the pinned task Python and Torch versions')
    if not Path('/app/weights.pt').is_file() or not Path('/app/dataset.pt').is_file():
        raise ValueError('expected the task guest inputs')
    output = Path('/logs/verifier/torch-wheel-sharing.json')
    output.parent.mkdir(parents=True, exist_ok=True)
    report = {'scope': 'repaired oracle dependency layout; original verifier and limits',
              'status': 'running', 'packages': []}
    try:
        # Remove only the task VM's disposable pip download cache. No uv cache
        # internals are edited, and no installed package is removed manually.
        subprocess.run([sys.executable, '-m', 'pip', 'cache', 'purge'], check=True)
        subprocess.run([sys.executable, '-m', 'pip', 'install', '--no-cache-dir',
                        '--index-url', 'https://pypi.org/simple', 'uv==0.9.5'], check=True)
        uv = Path(sysconfig.get_path('scripts')) / 'uv'
        if subprocess.check_output([str(uv), '--version'], text=True).strip() != 'uv 0.9.5':
            raise ValueError('unexpected uv version')
        versions = installed_versions()
        selected = []
        for name, version in sorted(versions.items()):
            if name in ('torch', 'triton') or name.startswith('nvidia-'):
                if any(path.stat().st_size >= LARGE_FILE_BYTES
                       for _, path in payload_files(metadata.distribution(name))):
                    selected.append((name, version))
        if not any(name == 'torch' for name, _ in selected):
            raise ValueError('expected installed large Torch payload')
        with tempfile.TemporaryDirectory(prefix='sandproof-wheel-sharing-') as temporary:
            root = Path(temporary)
            for name, version in selected:
                report['current_package'] = name
                resolution = root / 'resolution.json'
                subprocess.run([sys.executable, '-m', 'pip', 'install', '--dry-run',
                                '--ignore-installed', '--no-deps', '--no-cache-dir',
                                '--only-binary=:all:', '--index-url', 'https://pypi.org/simple',
                                '--report', str(resolution), f'{name}=={version}'], check=True)
                requirements = root / 'requirements.txt'
                requirements.write_text(wheel_requirement(json.loads(resolution.read_text()), name, version))
                result = relink(name, version, requirements, uv)
                result['requirement'] = requirements.read_text().strip()
                report['packages'].append(result)
                output.write_text(json.dumps(report, indent=2) + '\n')
        if installed_versions() != versions:
            raise ValueError('dependency versions changed')
        report['status'] = 'passed'
    except Exception as error:
        report.update(status='failed', error_type=type(error).__name__)
        raise
    finally:
        output.write_text(json.dumps(report, indent=2) + '\n')


if __name__ == '__main__':
    main()
