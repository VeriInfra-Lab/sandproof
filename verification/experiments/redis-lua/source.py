"""Import the two literal Lua inputs, never a replacement CAS implementation.

The finite Rust layout is admitted in full. This is input/source evidence, not
a Rust parser or a correctness proof of the Lua scripts or their callers.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[3]
SCRIPTS = Path('sandbox-center-store/src/scripts.rs')
STORE = Path('sandbox-center-store/src/store.rs')
SCRIPT_DECLARATION = re.compile(
    r'pub\(crate\) const (READ|CAS): &str = r"(.*?)";', re.DOTALL
)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def mutants(source):
    """Actual Lua variants; native and Lean checks consume these same bytes."""
    write = b"  redis.call('HSET', KEYS[1], 'revision', ARGV[4])"
    start = b"local kind = redis.call('TYPE', KEYS[1]).ok\n"
    if source.count(write) != 1 or source.count(start) != 1:
        raise ValueError('counterexample edits no longer match their original source')
    return {
        'skip-reaffirm-write': source.replace(write, b'  return 0'),
        'write-before-guards': source.replace(start, start + write.strip() + b'\n'),
    }


def scripts_from_bytes(raw):
    """Reject extra Rust, duplicate constants and unreviewed string forms."""
    if len(raw) > 16 * 1024:
        raise ValueError('Lua source container exceeds the reviewed input size')
    source = raw.decode('ascii')
    matches = list(SCRIPT_DECLARATION.finditer(source))
    if [m[1] for m in matches] != ['READ', 'CAS']:
        raise ValueError('expected exactly the original READ and CAS literal declarations')
    remaining = SCRIPT_DECLARATION.sub('', source)
    remaining = re.sub(r'//[^\n]*', '', remaining)
    if remaining.strip():
        raise ValueError('unreviewed Rust outside the two raw string constants')
    scripts = {m[1]: m[2].encode('ascii') for m in matches}
    if any(not value or b'\0' in value for value in scripts.values()):
        raise ValueError('empty or NUL-containing source input')
    return scripts


def source_record(root=ROOT):
    raw = (root / SCRIPTS).read_bytes()
    scripts = scripts_from_bytes(raw)
    return {
        'schema': 1,
        'scope': 'literal input import only; not a Lua or Rust correctness result',
        'container': {'path': SCRIPTS.as_posix(), 'sha256': digest(raw)},
        'caller': {'path': STORE.as_posix(), 'sha256': digest((root / STORE).read_bytes())},
        'scripts': {name: {'bytes': len(data), 'sha256': digest(data)}
                    for name, data in scripts.items()},
    }, scripts


def lean_source(scripts):
    """Literal-only emission; parsing/semantics are checked separately in Lean."""
    lines = ['import SandboxModel.CenterStore.Lua.Syntax', '',
             '-- Generated by verification/experiments/redis-lua/source.py.',
             '-- Exact ASCII source inputs. No AST, proof or execution is imported.',
             'namespace Sandproof.CenterStore.Lua', '']
    inputs = {name.lower(): value for name, value in scripts.items()}
    bad = mutants(scripts['CAS'])
    inputs.update(skipReaffirm=bad['skip-reaffirm-write'], earlyWrite=bad['write-before-guards'])
    for name, value in inputs.items():
        # These escapes coincide for this ASCII-only, NUL-free input domain.
        literal = json.dumps(value.decode('ascii'), ensure_ascii=True)
        lines.append(f'def {name}Source : String := {literal}')
        lines.append(f'def {name}Chars : List Char := luaChars% {literal}')
        lines.append('')
    lines.append('end Sandproof.CenterStore.Lua')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-root', type=Path, default=ROOT)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    record, scripts = source_record(args.source_root.resolve())
    args.output.mkdir(parents=True, exist_ok=False)
    for name, raw in scripts.items():
        (args.output / (name.lower() + '.lua')).write_bytes(raw)
    (args.output / 'RawSource.lean').write_text(lean_source(scripts))
    (args.output / 'source.json').write_text(json.dumps(record, indent=2) + '\n')
    print(json.dumps(record))


if __name__ == '__main__':
    main()
