"""Check fresh parent/source captures and both real collection variants.

Compiler success, complete raw outputs and precise source/IR roots are all
required. A mutant compile/import failure is never a property counterexample.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import tarfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def check(source, parent, correct, mutant, project, output):
    output.mkdir(mode=0o700)
    result = dict(development_only=True, public_acceptance=False, complete=False, variants={})
    try:
        spec = importlib.util.spec_from_file_location('original_parent_check', HERE.parent / 'unload-parent-link/check_capture.py')
        original = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(original)
        original.check(source, parent, project, output / 'parent')
        parent_result = json.loads((output / 'parent/result.json').read_bytes())
        profile = json.loads((HERE / 'capture-profile.json').read_bytes())
        raw_outputs = json.loads((HERE / 'raw-outputs.json').read_bytes())
        fixed = json.loads((ROOT / 'verification/foundations-environment.json').read_bytes())
        head = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
        base = (ROOT / profile['source']).read_bytes()
        if hashlib.sha256(base).hexdigest() != profile['source_sha256']:
            raise ValueError('current actual collection source changed')
        archives = set()
        for variant, directory in [('correct', correct), ('attempt-zero', mutant)]:
            report = json.loads((directory / 'result.json').read_bytes())
            if (report.get('complete') is not True or report.get('variant') != variant
                    or report.get('native_acceptance') is not False or report.get('public_acceptance') is not False
                    or report['head'] != head or report['profile_sha256'] != sha(HERE / 'capture-profile.json')
                    or report['ir_sha256'] != sha(directory / 'actual.llbc')
                    or report['source_archive_sha256'] != sha(directory / 'source.tar')):
                raise ValueError('incomplete/changed collection capture: ' + variant)
            archives.add(report['source_archive_sha256'])
            if report['binary_sha256'] != {key: fixed[key]['binary_sha256'] for key in ['charon', 'aeneas']}:
                raise ValueError('different fixed extraction tools')
            commands = report['commands']
            if len(commands) != 2 or [row['label'] for row in commands] != ['charon', 'aeneas']:
                raise ValueError('missing actual extraction commands')
            for row in commands:
                if (row['exit_code'] != 0 or row.get('bounded_stop') or row.get('interrupted')
                        or row['log_sha256'] != sha(directory / (row['label'] + '.log'))):
                    raise ValueError('extractor did not complete: ' + variant)
            published = ROOT / 'verification/aeneas/stage1-protocol/unload-parent-collections' / variant
            actual_files = {str(path.relative_to(directory / 'generated')): sha(path)
                            for path in (directory / 'generated').rglob('*') if path.is_file()}
            if actual_files != report['generated'] or len(actual_files) != 5:
                raise ValueError('partial or changed raw generated output')
            if actual_files != raw_outputs[variant]:
                raise ValueError('raw collection outputs differ from the reviewed candidate')
            for name, expected in actual_files.items():
                # Unimported external templates stay byte-for-byte in private
                # raw evidence. Publish actual bodies and translation metadata.
                if name.endswith('_Template.lean'):
                    continue
                if sha(published / name) != expected:
                    raise ValueError('published collection output was not generated by this capture')
            expected_source = base
            if variant == 'attempt-zero':
                before = profile['mutation']['before'].encode()
                if base.count(before) != 1:
                    raise ValueError('field omission is not unique')
                expected_source = base.replace(before, profile['mutation']['after'].encode())
            if (directory / 'source' / profile['source']).read_bytes() != expected_source:
                raise ValueError('isolated actual Rust differs from the declared variant')
            with tarfile.open(directory / 'source.tar') as archive:
                if archive.extractfile(profile['source']).read() != base:
                    raise ValueError('capture did not begin with the current exact source')
            ir = json.loads((directory / 'actual.llbc').read_bytes())
            if ir['has_errors'] is not False:
                raise ValueError('LLBC contains extraction errors')
            translated = ir['translated']
            if translated['crate_name'] != 'sandproof_controller_service':
                raise ValueError('wrong actual crate')
            targets = translated['target_information']
            if (len(targets) != 1 or targets[0]['key'] != fixed['target']
                    or targets[0]['value']['target_pointer_size'] != 8
                    or targets[0]['value']['is_little_endian'] is not True):
                raise ValueError('actual target differs from the original 64-bit environment')
            for key, ir_key in [('roots', 'start_from'), ('include', 'include'), ('opaque', 'opaque')]:
                if translated['options'][ir_key] != profile['configuration'][key]:
                    raise ValueError('actual root/opaque selection changed')
            roots = []
            for name in profile['configuration']['roots']:
                declarations = [row for row in translated['fun_decls'] if row is not None and
                    row['item_meta']['name'] == [{'Ident': [part, 0]} for part in name.split('::')]]
                if len(declarations) != 1:
                    raise ValueError('missing or duplicated actual root: ' + name)
                row = declarations[0]
                meta = row['item_meta']
                if (not row.get('body') or meta['opacity'] != 'Transparent' or meta['is_local'] is not True
                        or not meta['source_text'] or meta['source_text'].encode() not in expected_source):
                    raise ValueError('actual root is opaque or from different Rust')
                roots.append(dict(name=name, source_text_sha256=hashlib.sha256(meta['source_text'].encode()).hexdigest()))
            result['variants'][variant] = dict(head=head, ir_sha256=report['ir_sha256'], roots=roots,
                actual_generated=actual_files, source_sha256=hashlib.sha256(expected_source).hexdigest())
        if len(archives) != 1 or any(parent_result[key]['source_base'] != head for key in ['source', 'parent']):
            raise ValueError('captures are not from the same exact candidate')
        for name in ['Types.lean', 'Funs.lean']:
            if ((project / 'SandproofUnloadFirstCollections' / name).read_bytes() !=
                    (correct / 'generated/SandproofUnloadFirstCollections' / name).read_bytes()):
                raise ValueError('actual parent project does not import the freshly generated collector')
        result['complete'] = True
    except BaseException as error:
        result['error'] = repr(error)
    finally:
        (output / 'result.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(dict(complete=result['complete'], error=result.get('error'), development_only=True)))
    return not result['complete']


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ['source', 'parent', 'correct', 'mutant', 'project', 'output']:
        parser.add_argument('--' + name, type=Path, required=True)
    args = parser.parse_args()
    raise SystemExit(check(args.source.resolve(strict=True), args.parent.resolve(strict=True),
        args.correct.resolve(strict=True), args.mutant.resolve(strict=True),
        args.project.resolve(strict=True), args.output.resolve()))
